//! Contract for the asset store (spec v3 §7): binaries (images, meshes, audio, weights, renders) live in a
//! content-addressed store, each with a [`Provenance`] record, and the [`licence_gate`] decides what may leave the
//! machine (§40: nothing non-commercial, ever).
//!
//! Why content addressing: the same bytes are stored once (dedup is automatic), project files reference assets by
//! hash so they stay small and mergeable, and a hash proves exactly which bytes a render or export used.
#![deny(missing_docs)]

use std::fmt;
use std::str::FromStr;
use std::time::{Duration, SystemTime};

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// A BLAKE3 hash of an asset's bytes, written as 64 lowercase hex characters.
#[derive(Copy, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, JsonSchema)]
#[serde(try_from = "String", into = "String")]
#[schemars(with = "String")]
pub struct ContentHash(pub [u8; 32]);

impl ContentHash {
    /// The BLAKE3 hash of `bytes`: the one place the hash function is chosen, so stores, mocks and test helpers
    /// cannot disagree about what an asset's name is.
    pub fn of(bytes: &[u8]) -> Self {
        Self(*blake3::hash(bytes).as_bytes())
    }
}

/// Why a string isn't a [`ContentHash`].
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("a content hash is 64 lowercase hex characters; got {0:?}")]
pub struct HashParseError(pub String);

impl FromStr for ContentHash {
    type Err = HashParseError;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let bad = || HashParseError(s.to_owned());
        if s.len() != 64 || !s.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)) {
            return Err(bad());
        }
        let mut out = [0u8; 32];
        for (i, byte) in out.iter_mut().enumerate() {
            *byte = u8::from_str_radix(&s[2 * i..2 * i + 2], 16).map_err(|_| bad())?;
        }
        Ok(Self(out))
    }
}

impl TryFrom<String> for ContentHash {
    type Error = HashParseError;
    fn try_from(s: String) -> Result<Self, Self::Error> {
        s.parse()
    }
}

impl From<ContentHash> for String {
    fn from(h: ContentHash) -> Self {
        h.to_string()
    }
}

impl fmt::Display for ContentHash {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.iter().try_for_each(|b| write!(f, "{b:02x}"))
    }
}

impl fmt::Debug for ContentHash {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "ContentHash({})", &self.to_string()[..12])
    }
}

/// Whether an asset may be used commercially (§7). `Unknown` is treated as `No` by the gate (§40).
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum Commercial {
    /// Cleared for commercial use.
    Ok,
    /// Not allowed commercially.
    No,
    /// Not established: blocked until someone clears it.
    Unknown,
}

/// Where an asset came from and what may be done with it. Every asset has one; the gate reads nothing else.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct Provenance {
    /// What produced it: a tool, model or person.
    pub source: Source,
    /// Who made or owns it, as the licence names them.
    pub author: Option<String>,
    /// SPDX licence expression (`CC0-1.0`, `CC-BY-4.0`) or `LicenseRef-<name>` for a custom record.
    pub licence: String,
    /// Attribution text that must travel with it (CC BY and similar).
    pub attribution: Option<String>,
    /// Commercial status.
    pub commercial: Commercial,
    /// Likeness or voice consent, when a real person is involved.
    pub consent: Option<Consent>,
    /// Private test material (fan art, test clips): never shippable, whatever its other fields say (§40).
    pub private_test: bool,
}

/// What produced an asset.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Source {
    /// Made in Omuzaki by ops (the op log has the details).
    Authored,
    /// Imported from a file.
    Imported {
        /// The file name it came from.
        file: String,
        /// Where the user got it (URL or description).
        origin: Option<String>,
    },
    /// Generated by a connector or model.
    Generated {
        /// The tool or service (`comfyui`, `meshy`).
        tool: String,
        /// The model and version.
        model: String,
        /// The service plan tier, which decides ownership for some vendors (§14).
        plan: Option<String>,
        /// The prompt, if any.
        prompt: Option<String>,
        /// The seed, if any.
        seed: Option<u64>,
        /// Hashes of input assets (reference images and so on).
        inputs: Vec<ContentHash>,
    },
    /// From the built-in library.
    Library {
        /// Item id and version, `id@version`.
        item: String,
    },
}

/// Consent recorded for a real person's likeness or voice.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct Consent {
    /// Who consented.
    pub person: String,
    /// What they consented to (e.g. "voice cloning for this channel").
    pub scope: String,
    /// Hash of the stored consent document.
    pub document: Option<ContentHash>,
}

/// Why the gate blocked an asset: shown to the user and to agents as-is, so it says what to do.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error, Serialize, Deserialize, JsonSchema)]
pub enum GateError {
    /// The licence or terms don't allow commercial use.
    #[error("not cleared for commercial use ({licence}); replace it or keep it out of anything published")]
    NonCommercial {
        /// The licence on record.
        licence: String,
    },
    /// Commercial status was never established.
    #[error("its licence is unknown ({licence}); record where it came from and its licence, then publish")]
    Unknown {
        /// The licence on record.
        licence: String,
    },
    /// Marked as private test material.
    #[error("it's private test material and can never be published")]
    PrivateTest,
    /// A real person is involved and no consent is recorded.
    #[error("a real person's likeness or voice needs a recorded consent before publishing")]
    NoConsent,
}

/// The licence gate (§7, §40): may this asset leave the machine in something published?
///
/// # Errors
/// The first reason it may not, in the order a user should fix them.
pub fn licence_gate(p: &Provenance, involves_real_person: bool) -> Result<(), GateError> {
    if p.private_test {
        return Err(GateError::PrivateTest);
    }
    match p.commercial {
        Commercial::No => return Err(GateError::NonCommercial { licence: p.licence.clone() }),
        Commercial::Unknown => return Err(GateError::Unknown { licence: p.licence.clone() }),
        Commercial::Ok => {}
    }
    if involves_real_person && p.consent.is_none() {
        return Err(GateError::NoConsent);
    }
    Ok(())
}

/// Why a store operation failed.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum StoreError {
    /// No asset with that hash.
    #[error("no asset {0}")]
    Missing(ContentHash),
    /// The stored bytes don't match their hash (disk corruption or tampering).
    #[error("asset {0} is corrupt: its bytes no longer match the hash")]
    Corrupt(ContentHash),
    /// An I/O problem, with the OS message.
    #[error("store I/O failed: {0}")]
    Io(String),
}

/// A content-addressed asset store. `put` is idempotent: the same bytes always give the same hash.
pub trait Store: Send + Sync {
    /// Stores `bytes` with their provenance; returns the hash. Storing existing bytes again keeps the first
    /// provenance and returns the same hash.
    ///
    /// # Errors
    /// [`StoreError::Io`] if writing fails.
    fn put(&self, bytes: &[u8], provenance: Provenance) -> Result<ContentHash, StoreError>;

    /// The bytes for `hash`, verified against it.
    ///
    /// # Errors
    /// [`StoreError::Missing`], [`StoreError::Corrupt`] or [`StoreError::Io`].
    fn get(&self, hash: &ContentHash) -> Result<Vec<u8>, StoreError>;

    /// The provenance for `hash`.
    ///
    /// # Errors
    /// [`StoreError::Missing`] or [`StoreError::Io`].
    fn provenance(&self, hash: &ContentHash) -> Result<Provenance, StoreError>;

    /// True if the store holds `hash`.
    fn contains(&self, hash: &ContentHash) -> bool;

    /// The stored length of `hash` in bytes, without reading them, so a caller can refuse an asset over its cap before
    /// fetching it. The length is the store's record, not verified against the hash: [`get`](Self::get) still checks
    /// the bytes. The default reads through `get`; every store in the workspace answers without reading.
    ///
    /// # Errors
    /// [`StoreError::Missing`] or [`StoreError::Io`] (and, from the default, what `get` returns).
    fn size(&self, hash: &ContentHash) -> Result<u64, StoreError> {
        self.get(hash).map(|bytes| bytes.len() as u64)
    }
}

/// What [`StoreGc::sweep`] did.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SweepReport {
    /// The objects removed, in hash order.
    pub removed: Vec<ContentHash>,
    /// Objects left in place: kept by the caller's predicate, or younger than the grace period.
    pub kept: usize,
    /// Leftovers of an earlier interrupted removal that this sweep deleted first (see [`StoreGc::purge_retired`]).
    pub purged: usize,
}

/// What [`StoreGc::remove_if_older`] did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Removal {
    /// The object was old enough and has been removed.
    Removed,
    /// The store didn't hold the object.
    Absent,
    /// The object was committed or freshened after the cutoff, or its commit is still running, so it was left alone.
    Fresh,
}

/// Listing and removal for garbage collection (ADR 0021, journal §7.3). A store never decides on its own what is
/// garbage: the keeper works that out from the snapshots and calls [`StoreGc::sweep`].
///
/// A store may have several writers, in this process or others, so `sweep` can run while a `put` is in flight. What
/// protects a new object is the grace period: the commit time an implementation reports must be no earlier than the
/// moment `put` returned by more than a quarter of the grace, and no earlier at all if the sweeping process is the one
/// that wrote the object. After a power cut or crash a commit time may be lost or rolled back, which is harmless: every
/// caller that could hold an uncommitted reference is gone, and `put` made the data durable before it returned, so an
/// object that no durable state references is garbage.
///
/// A `put` of bytes the store already holds freshens the object: its commit time becomes the time of that `put` (unless
/// it is already within a quarter of the grace of it), so a writer that re-puts an old, unreferenced object gets the
/// same grace as one that stores it for the first time. [`StoreGc::remove_if_older`] is atomic with `put` of the same
/// object: it re-reads the commit time at the moment of removal, so a removal can't take an object that a `put`
/// committed or freshened after the cutoff, however many collectors run.
pub trait StoreGc: Store {
    /// Every object the store holds, sorted by hash. Includes objects whose data or provenance is damaged, so that a
    /// sweep can clear them.
    ///
    /// # Errors
    /// [`StoreError::Io`] if the store can't be listed.
    fn hashes(&self) -> Result<Vec<ContentHash>, StoreError>;

    /// When the object was committed. Its age is judged against this.
    ///
    /// # Errors
    /// [`StoreError::Missing`] if the store doesn't hold `hash`, or [`StoreError::Io`].
    fn stored_at(&self, hash: &ContentHash) -> Result<SystemTime, StoreError>;

    /// Removes the object and its provenance if it was committed (or freshened) no later than `cutoff`, deciding
    /// atomically with removing: a `put` of the same object either finishes first, and the object is
    /// [`Removal::Fresh`], or starts after, and stores it again. Afterwards `contains` is false and a `put` of the same
    /// bytes stores it again. An object whose commit is still running is `Fresh`.
    ///
    /// # Errors
    /// [`StoreError::Io`]. A failure part-way never leaves an object without its data.
    fn remove_if_older(&self, hash: &ContentHash, cutoff: SystemTime) -> Result<Removal, StoreError>;

    /// Deletes what an interrupted [`StoreGc::remove_if_older`] left behind. The object was already judged garbage, so
    /// nothing is kept for it: it is deleted, not quarantined. Returns how many leftovers were deleted.
    ///
    /// # Errors
    /// [`StoreError::Io`]. Whatever was not deleted is found again by the next call.
    fn purge_retired(&self) -> Result<usize, StoreError>;

    /// Removes every object that `keep` rejects and that was committed at least `grace` before `now`. Anything else is
    /// left alone, so a young object (written for a ref not yet published) is never taken, even if a `put` freshens it
    /// while the sweep runs. Several sweeps may run at once. Leftovers of an interrupted removal are purged first.
    /// Stops at the first error; what was removed before it stays removed, and running again finishes the job.
    ///
    /// `now` is the wall clock: callers pass the current time, and tests pass a fixed instant, so the result depends
    /// only on the arguments and the store.
    ///
    /// # Errors
    /// The first [`StoreError`] from purging, listing, inspecting or removing an object.
    fn sweep(
        &self,
        keep: &dyn Fn(&ContentHash) -> bool,
        grace: Duration,
        now: SystemTime,
    ) -> Result<SweepReport, StoreError> {
        let mut report = SweepReport { purged: self.purge_retired()?, ..SweepReport::default() };
        for hash in self.hashes()? {
            let stored = match self.stored_at(&hash) {
                Ok(stored) => stored,
                // Removed by someone else since we listed it: nothing to do.
                Err(StoreError::Missing(_)) => continue,
                Err(e) => return Err(e),
            };
            // A commit time in the future (an unmarked object's, or clock skew) is not old, even for zero grace.
            let old_enough = now.duration_since(stored).is_ok_and(|age| age >= grace);
            if keep(&hash) || !old_enough {
                report.kept += 1;
                continue;
            }
            // The check above can be stale by now: a `put` may have freshened the object. The removal decides again.
            let cutoff = now.checked_sub(grace).unwrap_or(SystemTime::UNIX_EPOCH);
            match self.remove_if_older(&hash, cutoff)? {
                Removal::Removed => report.removed.push(hash),
                Removal::Absent => {}
                Removal::Fresh => report.kept += 1,
            }
        }
        Ok(report)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn prov(commercial: Commercial) -> Provenance {
        Provenance {
            source: Source::Authored,
            author: None,
            licence: "LicenseRef-Omuzaki-User".into(),
            attribution: None,
            commercial,
            consent: None,
            private_test: false,
        }
    }

    #[test]
    fn of_is_blake3_of_the_bytes() {
        // The published BLAKE3 test vector for the empty input.
        assert_eq!(
            ContentHash::of(b"").to_string(),
            "af1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262"
        );
        assert_eq!(ContentHash::of(b"abc"), ContentHash::of(b"abc"), "deterministic");
        assert_ne!(ContentHash::of(b"abc"), ContentHash::of(b"abd"));
    }

    #[test]
    fn hash_hex_round_trip_and_validation() {
        let h = ContentHash([0xab; 32]);
        let s = h.to_string();
        assert_eq!(s.len(), 64);
        assert_eq!(s.parse::<ContentHash>().unwrap(), h);
        assert!("AB".repeat(32).parse::<ContentHash>().is_err(), "uppercase is rejected");
        assert!("ab".repeat(31).parse::<ContentHash>().is_err());
        assert_eq!(serde_json::to_string(&h).unwrap(), format!("\"{s}\""));
    }

    #[test]
    fn gate_blocks_no_unknown_private_and_unconsented() {
        assert!(licence_gate(&prov(Commercial::Ok), false).is_ok());
        assert!(matches!(licence_gate(&prov(Commercial::No), false), Err(GateError::NonCommercial { .. })));
        assert!(matches!(licence_gate(&prov(Commercial::Unknown), false), Err(GateError::Unknown { .. })));
        let private = Provenance { private_test: true, ..prov(Commercial::Ok) };
        assert_eq!(licence_gate(&private, false), Err(GateError::PrivateTest));
        assert_eq!(licence_gate(&prov(Commercial::Ok), true), Err(GateError::NoConsent));
        let consented = Provenance {
            consent: Some(Consent { person: "owner".into(), scope: "likeness".into(), document: None }),
            ..prov(Commercial::Ok)
        };
        assert!(licence_gate(&consented, true).is_ok());
    }
}

//! Embeds the look presets in `library/looks/` (LK-06), the character styles in `library/styles/`, the hairstyles in
//! `library/hair-styles/` (#2486) and the library items in `library/items/`: writes `looks.rs`, `styles.rs`,
//! `hair_styles.rs`, `items.rs` and `dials.rs` (the design library's dials, `library/dials/`) with one `(id, text)` entry per `<id>.toml` file, in name order, so a preset is added by adding a
//! file and no list in code names them (spec v3 §39 rules 2 and 5). The crate parses them once (`src/look/mod.rs`,
//! `src/style.rs`).

#![allow(
    clippy::disallowed_methods,
    reason = "a build script lists and writes files at build time; the fence is for ops"
)]

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs, process};

/// The folder of preset files, relative to the crate.
const LOOKS: &str = "library/looks";

/// The folder of character styles, relative to the crate.
const STYLES: &str = "library/styles";

/// The folder of whole hairstyles, relative to the crate.
const HAIR_STYLES: &str = "library/hair-styles";

/// The folder of first-party library items (`omuzaki-library-api`'s manifests), relative to the crate.
const ITEMS: &str = "library/items";

/// The folder of the design library's dials and age model (#2612, #2615), relative to the crate.
const DIALS: &str = "library/dials";

/// The folder of op families, relative to the crate: its children are declared as modules (ADR 0054).
const OPS: &str = "src/ops";

fn main() {
    println!("cargo::rerun-if-changed={LOOKS}");
    println!("cargo::rerun-if-changed={STYLES}");
    println!("cargo::rerun-if-changed={HAIR_STYLES}");
    println!("cargo::rerun-if-changed={ITEMS}");
    println!("cargo::rerun-if-changed={DIALS}");
    if let Err(message) = generate() {
        println!("cargo::error={message}");
        process::exit(1);
    }
}

fn generate() -> Result<(), String> {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR isn't set")?);
    let out = PathBuf::from(env::var_os("OUT_DIR").ok_or("OUT_DIR isn't set")?);
    embed(&manifest, LOOKS, &out.join("looks.rs"))?;
    embed(&manifest, STYLES, &out.join("styles.rs"))?;
    embed(&manifest, HAIR_STYLES, &out.join("hair_styles.rs"))?;
    embed(&manifest, ITEMS, &out.join("items.rs"))?;
    embed(&manifest, DIALS, &out.join("dials.rs"))?;
    omuzaki_embed::modules(manifest.join(OPS), out.join("ops_mods.rs"), "pub")
        .map_err(|e| format!("can't declare the ops modules: {e}"))
}

/// Writes `out`: a `FILES` table of every `<id>.toml` of the crate's folder `folder`, as `(file stem, text)`.
fn embed(manifest: &Path, folder: &str, out: &Path) -> Result<(), String> {
    let mut entries = String::new();
    for (id, path) in preset_files(&manifest.join(folder), folder)? {
        writeln!(entries, "    ({id:?}, include_str!({:?})),", path.display().to_string())
            .map_err(|e| format!("can't list {folder}: {e}"))?;
    }
    let source = format!(
        "/// Every file of `{folder}/` as `(file stem, text)`, in name order (generated by `build.rs`).\n\
         static FILES: &[(&str, &str)] = &[\n{entries}];\n"
    );
    fs::write(out, source).map_err(|e| format!("can't write {}: {e}", out.display()))
}

/// The `.toml` files of `dir` as `(stem, path)`, sorted by stem. Anything else in the folder is refused, so a
/// misnamed preset can't be silently left out.
fn preset_files(dir: &Path, folder: &str) -> Result<Vec<(String, PathBuf)>, String> {
    let listing = fs::read_dir(dir).map_err(|e| format!("can't list {}: {e}", dir.display()))?;
    let mut files = Vec::new();
    for entry in listing {
        let path = entry.map_err(|e| format!("can't list {}: {e}", dir.display()))?.path();
        let stem = path.file_stem().and_then(|s| s.to_str()).map(str::to_owned);
        match (stem, path.extension().and_then(|e| e.to_str())) {
            (Some(stem), Some("toml")) => files.push((stem, path)),
            _ => return Err(format!("{} is out of place: {folder}/ holds only <id>.toml files", path.display())),
        }
    }
    files.sort();
    Ok(files)
}

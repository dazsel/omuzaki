//! The model scan (ADR 0061 decision 2, design §5): one bounded pass over a TFLite FlatBuffer, before any LiteRT code
//! sees the bytes, that accepts exactly design §5's allow-list and refuses everything else with a named [`LoadError`]
//! (`Refused` for a feature we don't run, `Format` for malformed bytes).
//!
//! The official `flatbuffers` crate does the reading: its verifier checks every table, vector and string the scan reads
//! (offsets, vtables, alignment, lengths, UTF-8), and only then are fields read through its accessors. What is written
//! here is the field list of the ten tables the allow-list reads, by slot, from `tflite/converter/schema/schema.fbs` at
//! LiteRT `v2.3.0` (#1749 records why it is not generated by `flatc`). A slot past a table's last is a field newer than
//! that schema and is refused when set, so a model from a newer converter fails closed.
//!
//! The scan never follows a buffer's data, only table fields, so its work is linear in the tables, not the weights.
#![allow(unsafe_code)] // `flatbuffers::Table::get` is `unsafe`; `Fields::get` carries the argument that it is sound.

use std::collections::BTreeSet;
use std::ops::RangeInclusive;

use flatbuffers::{
    Follow, ForwardsUOffset, InvalidFlatbuffer, Table, TableVerifier, VOffsetT, Vector, Verifiable, Verifier,
    VerifierOptions,
};
use omuzaki_ai_api::{DType, Dim, LoadError, MAX_RANK, Signature, TensorSpec};

use crate::builds::SCHEMA_VERSION;

/// The largest model file read, above any slot's model (the face landmark graph is 2.5 MB).
pub const MAX_MODEL_BYTES: usize = 256 << 20;
/// The most tensors in the subgraph.
pub const MAX_TENSORS: usize = 1 << 16;
/// The most operators in the subgraph, and the most operator codes.
pub const MAX_OPERATORS: usize = 1 << 16;
/// The most buffers.
pub const MAX_BUFFERS: usize = 1 << 16;
/// The most metadata entries.
pub const MAX_METADATA: usize = 16;
/// The most graph inputs, and the most graph outputs.
pub const MAX_PORTS: usize = 64;
/// The longest port name, and the longest model description.
pub const MAX_NAME_BYTES: usize = 1024;
/// The most tables the verifier visits: every table the caps above allow, a quantization table per tensor included.
const MAX_TABLES: usize = 4 + 2 * MAX_TENSORS + 2 * MAX_OPERATORS + MAX_BUFFERS + MAX_METADATA + 2 * MAX_PORTS;

/// The metadata names that only describe the model; any other (`reduced_precision_support`, say) can change how the
/// interpreter computes, so it is refused.
const METADATA_NAMES: &[&str] = &["min_runtime_version", "CONVERSION_METADATA", "TFLITE_METADATA"];

/// What the scan read from an accepted model.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Scan {
    /// The graph's inputs and outputs, with the model's names; `-1` in `shape_signature` is [`Dim::ANY`].
    pub signature: Signature,
}

/// Scans `bytes` as a TFLite model.
///
/// # Errors
/// [`LoadError::Format`] for bytes that are not a well-formed TFLite FlatBuffer, [`LoadError::Refused`] for anything
/// off the allow-list.
pub fn scan_model(bytes: &[u8]) -> Result<Scan, LoadError> {
    if bytes.len() > MAX_MODEL_BYTES {
        return Err(refused(format!("the model is larger than MAX_MODEL_BYTES ({MAX_MODEL_BYTES} bytes)")));
    }
    if bytes.len() < 8 || !flatbuffers::buffer_has_identifier(bytes, "TFL3", false) {
        return Err(malformed("no TFL3 file identifier"));
    }
    let options = VerifierOptions { max_tables: MAX_TABLES, ..VerifierOptions::default() };
    let mut verifier = Verifier::new(&options, bytes);
    <ForwardsUOffset<ModelV>>::run_verifier(&mut verifier, 0).map_err(|error| match error {
        InvalidFlatbuffer::TooManyTables => malformed(&format!("more than MAX_TABLES ({MAX_TABLES}) tables")),
        other => malformed(&other.to_string()),
    })?;
    // SAFETY: the verifier just checked the root offset and the table it points to.
    let model = Fields::new(unsafe { <ForwardsUOffset<Table<'_>>>::follow(bytes, 0) }, "Model", 10)?;
    model_checks(model)
}

/// A table the verifier passed, read through the crate's accessors.
#[derive(Clone, Copy)]
struct Fields<'a> {
    table: Table<'a>,
}

impl<'a> Fields<'a> {
    /// `table`, refused when a slot past its pinned schema's `slots` is set.
    fn new(table: Table<'a>, name: &str, slots: u16) -> Result<Self, LoadError> {
        let vtable = table.vtable();
        let bytes = vtable.num_bytes();
        if bytes < 4 {
            return Err(malformed(&format!("a {name} vtable shorter than its header")));
        }
        let fields = u16::try_from((bytes - 4) / 2).map_err(|_| malformed(&format!("a {name} vtable too long")))?;
        if (slots..fields).any(|slot| vtable.get(voff(slot)) != 0) {
            return Err(refused(format!(
                "a {name} field this runtime does not know (newer than schema v{SCHEMA_VERSION} at LiteRT 2.3.0)"
            )));
        }
        Ok(Self { table })
    }

    /// The field at `slot` as `T`, or `None` when it is absent. Every call names the type the verifier impl below
    /// checked for that slot of that table.
    fn get<T: Follow<'a> + 'a>(self, slot: u16) -> Option<T::Inner> {
        // SAFETY: the table came from the verifier's pass, which checked the field at `slot` as `T` (see the
        // `Verifiable` impls; each reader below uses the same type as its table's impl).
        unsafe { self.table.get::<T>(voff(slot), None) }
    }

    /// Whether `slot` is set, without reading it.
    fn has(self, slot: u16) -> bool {
        self.table.vtable().get(voff(slot)) != 0
    }

    fn ints(self, slot: u16) -> Vec<i32> {
        self.get::<ForwardsUOffset<Vector<'a, i32>>>(slot).map(|v| v.iter().collect()).unwrap_or_default()
    }

    fn len<T: Follow<'a> + 'a>(self, slot: u16) -> usize {
        self.get::<ForwardsUOffset<Vector<'a, T>>>(slot).map_or(0, |v| v.len())
    }

    fn tables(self, slot: u16, name: &str, slots: u16) -> Result<Vec<Fields<'a>>, LoadError> {
        let vector = self.get::<ForwardsUOffset<Vector<'a, ForwardsUOffset<Table<'a>>>>>(slot);
        vector.map_or(Ok(Vec::new()), |v| v.iter().map(|t| Fields::new(t, name, slots)).collect())
    }
}

/// The vtable offset of field `slot`.
const fn voff(slot: u16) -> VOffsetT {
    4 + 2 * slot
}

fn refused(why: String) -> LoadError {
    LoadError::Refused(why)
}

fn malformed(why: &str) -> LoadError {
    LoadError::Format(format!("not a TFLite model ({why})"))
}

/// Declares a table's verifier: each listed field checked as its type, by slot.
macro_rules! verifiable {
    ($name:ident: $($slot:literal => $ty:ty),* $(,)?) => {
        struct $name;
        impl Verifiable for $name {
            fn run_verifier(v: &mut Verifier<'_, '_>, pos: usize) -> Result<(), InvalidFlatbuffer> {
                let t: TableVerifier<'_, '_, '_> = v.visit_table(pos)?;
                $(let t = t.visit_field::<$ty>(stringify!($slot), voff($slot), false)?;)*
                t.finish();
                Ok(())
            }
        }
    };
}

type Tables<T> = ForwardsUOffset<Vector<'static, ForwardsUOffset<T>>>;
type Scalars<T> = ForwardsUOffset<Vector<'static, T>>;

verifiable!(ModelV: 0 => u32, 1 => Tables<OperatorCodeV>, 2 => Tables<SubGraphV>, 3 => ForwardsUOffset<&str>,
    4 => Tables<BufferV>, 5 => Scalars<i32>, 6 => Tables<MetadataV>, 7 => Tables<SignatureDefV>, 8 => Scalars<u32>,
    9 => Scalars<u32>);
verifiable!(SubGraphV: 0 => Tables<TensorV>, 1 => Scalars<i32>, 2 => Scalars<i32>, 3 => Tables<OperatorV>);
verifiable!(TensorV: 0 => Scalars<i32>, 1 => i8, 2 => u32, 3 => ForwardsUOffset<&str>,
    4 => ForwardsUOffset<QuantizationV>, 5 => bool, 7 => Scalars<i32>, 8 => bool, 9 => Scalars<u32>, 10 => u32);
verifiable!(QuantizationV: 0 => Scalars<f32>, 1 => Scalars<f32>, 2 => Scalars<f32>, 3 => Scalars<i64>);
verifiable!(OperatorV: 0 => u32, 1 => Scalars<i32>, 2 => Scalars<i32>, 5 => Scalars<u8>, 6 => i8, 7 => Scalars<bool>,
    8 => Scalars<i32>, 9 => u64, 10 => u64);
verifiable!(OperatorCodeV: 0 => i8, 1 => ForwardsUOffset<&str>, 2 => i32, 3 => i32);
verifiable!(BufferV: 0 => Scalars<u8>, 1 => u64, 2 => u64);
verifiable!(MetadataV: 0 => ForwardsUOffset<&str>, 1 => u32);
verifiable!(SignatureDefV: 0 => Tables<TensorMapV>, 1 => Tables<TensorMapV>, 4 => u32);
verifiable!(TensorMapV: 1 => u32);

fn model_checks(model: Fields<'_>) -> Result<Scan, LoadError> {
    let version = model.get::<u32>(0).unwrap_or(0);
    if version != SCHEMA_VERSION {
        return Err(refused(format!("schema version {version}; this runtime reads version {SCHEMA_VERSION}")));
    }
    if model.len::<u32>(8) + model.len::<u32>(9) > 0 {
        return Err(refused("the model keeps data in external buffers".to_owned()));
    }
    if model.get::<ForwardsUOffset<&str>>(3).is_some_and(|d| d.len() > MAX_NAME_BYTES) {
        return Err(refused(format!("a description longer than MAX_NAME_BYTES ({MAX_NAME_BYTES})")));
    }
    let buffers = model.tables(4, "Buffer", 3)?;
    cap(buffers.len(), MAX_BUFFERS, "buffers", "MAX_BUFFERS")?;
    for buffer in &buffers {
        if buffer.get::<u64>(1).unwrap_or(0) != 0 || buffer.get::<u64>(2).unwrap_or(0) != 0 {
            return Err(refused("a buffer keeps its data outside the model (offset and size)".to_owned()));
        }
    }
    let buffer = |index: u32| index_in(index, buffers.len(), "buffer");
    for index in model.ints(5) {
        buffer(u32::try_from(index).map_err(|_| malformed(&format!("metadata buffer {index}")))?)?;
    }
    let metadata = model.tables(6, "Metadata", 2)?;
    cap(metadata.len(), MAX_METADATA, "metadata entries", "MAX_METADATA")?;
    for entry in &metadata {
        let name = entry.get::<ForwardsUOffset<&str>>(0).unwrap_or("");
        if !METADATA_NAMES.contains(&name) {
            return Err(refused(format!("metadata `{name}`, which may change how the model computes")));
        }
        buffer(entry.get::<u32>(1).unwrap_or(0))?;
    }
    let codes = model.tables(1, "OperatorCode", 4)?.into_iter().map(operator_code).collect::<Result<Vec<_>, _>>()?;
    cap(codes.len(), MAX_OPERATORS, "operator codes", "MAX_OPERATORS")?;
    let subgraphs = model.tables(2, "SubGraph", 6)?;
    let [subgraph] = subgraphs.as_slice() else {
        return Err(refused(format!("{} subgraphs; this runtime runs exactly one (no control flow)", subgraphs.len())));
    };
    let tensors = subgraph.tables(0, "Tensor", 11)?;
    cap(tensors.len(), MAX_TENSORS, "tensors", "MAX_TENSORS")?;
    for tensor in &tensors {
        tensor_checks(*tensor, &buffer)?;
    }
    let signature_defs = model.tables(7, "SignatureDef", 5)?;
    cap(signature_defs.len(), 1, "signature defs", "one")?;
    for def in &signature_defs {
        if def.get::<u32>(4).unwrap_or(0) != 0 {
            return Err(malformed("a signature def names a second subgraph"));
        }
        for map in def.tables(0, "TensorMap", 2)?.into_iter().chain(def.tables(1, "TensorMap", 2)?) {
            index_in(map.get::<u32>(1).unwrap_or(0), tensors.len(), "tensor")?;
        }
    }
    let operators = subgraph.tables(3, "Operator", 14)?;
    cap(operators.len(), MAX_OPERATORS, "operators", "MAX_OPERATORS")?;
    for operator in &operators {
        operator_checks(*operator, codes.len(), tensors.len())?;
    }
    let port_list = |slot, kind| ports(*subgraph, slot, kind, &tensors, &buffers);
    let (inputs, outputs) = (port_list(1, "input")?, port_list(2, "output")?);
    if let Some(both) = inputs.iter().find(|i| outputs.contains(i)) {
        return Err(refused(format!("tensor {both} is both a graph input and a graph output")));
    }
    let specs = |list: &[usize]| list.iter().map(|&i| port_spec(tensors[i])).collect::<Result<Vec<_>, _>>();
    let signature = Signature { inputs: specs(&inputs)?, outputs: specs(&outputs)? };
    for (list, kind) in [(&signature.inputs, "input"), (&signature.outputs, "output")] {
        let mut seen = BTreeSet::new();
        if let Some(twice) = list.iter().find(|spec| !seen.insert(spec.name.as_str())) {
            return Err(refused(format!("two graph {kind}s are named `{}`", twice.name)));
        }
    }
    Ok(Scan { signature })
}

/// Refuses `count` over `max`, naming the cap.
fn cap(count: usize, max: usize, what: &str, constant: &str) -> Result<(), LoadError> {
    if count > max {
        return Err(refused(format!("{count} {what}, more than {constant} ({max})")));
    }
    Ok(())
}

/// `index` as a position in a list of `len`, or `Format`.
fn index_in(index: u32, len: usize, what: &str) -> Result<usize, LoadError> {
    usize::try_from(index).ok().filter(|&i| i < len).ok_or_else(|| malformed(&format!("{what} index {index} of {len}")))
}

/// The builtin code of an operator code on the allow-list, or why not.
fn operator_code(code: Fields<'_>) -> Result<i32, LoadError> {
    if let Some(custom) = code.get::<ForwardsUOffset<&str>>(1) {
        return Err(refused(format!("the custom operator `{custom}`; models may only use LiteRT's builtin operators")));
    }
    if code.get::<i32>(2).unwrap_or(1) < 1 {
        return Err(malformed("an operator version below 1"));
    }
    // The schema's rule: the deprecated byte holds codes below 127, the int32 field all of them.
    let builtin = i32::from(code.get::<i8>(0).unwrap_or(0)).max(code.get::<i32>(3).unwrap_or(0));
    match allowed(builtin) {
        Ok(()) => Ok(builtin),
        Err(why) => Err(refused(format!("the builtin operator {}: {why}", builtin_name(builtin)))),
    }
}

fn operator_checks(operator: Fields<'_>, codes: usize, tensors: usize) -> Result<(), LoadError> {
    index_in(operator.get::<u32>(0).unwrap_or(0), codes, "operator code")?;
    let tensor = |i: i32| index_in(u32::try_from(i).unwrap_or(u32::MAX), tensors, "tensor");
    for input in operator.ints(1).into_iter().filter(|&i| i != -1) {
        tensor(input)?;
    }
    for output in operator.ints(2) {
        tensor(output)?;
    }
    let mutating = operator.get::<ForwardsUOffset<Vector<'_, bool>>>(7);
    let custom_options = operator.len::<u8>(5) > 0
        || operator.get::<i8>(6).unwrap_or(0) != 0
        || operator.get::<u64>(9).unwrap_or(0) != 0
        || operator.get::<u64>(10).unwrap_or(0) != 0;
    let refusal = if mutating.is_some_and(|m| m.iter().any(|b| b)) {
        "an operator that mutates a variable input"
    } else if operator.len::<i32>(8) > 0 {
        "an operator with intermediate tensors"
    } else if custom_options {
        "an operator with custom options"
    } else if operator.has(11) || operator.has(12) {
        "an operator with `builtin_options_2`, which the allow-list does not list"
    } else {
        return Ok(());
    };
    Err(refused(refusal.to_owned()))
}

/// The element types an internal tensor may have: FLOAT32, FLOAT16, INT32, UINT8, INT64, BOOL, INT16, INT8.
const TENSOR_TYPES: &[i8] = &[0, 1, 2, 3, 4, 6, 7, 9];

fn tensor_checks(tensor: Fields<'_>, buffer: &dyn Fn(u32) -> Result<usize, LoadError>) -> Result<(), LoadError> {
    let name = tensor.get::<ForwardsUOffset<&str>>(3).unwrap_or("");
    let ty = tensor.get::<i8>(1).unwrap_or(0);
    if !TENSOR_TYPES.contains(&ty) {
        return Err(refused(format!("tensor `{name}` has element type {ty}, which this runtime does not run")));
    }
    let (shape, signature) = (tensor.ints(0), tensor.ints(7));
    if shape.len() > MAX_RANK || shape.iter().any(|&d| d < 0) {
        return Err(malformed(&format!("tensor `{name}` has a shape of rank over MAX_RANK ({MAX_RANK}) or below 0")));
    }
    let signature_fits = signature.is_empty()
        || signature.len() == shape.len() && signature.iter().zip(&shape).all(|(&s, &d)| s == -1 || s == d);
    if !signature_fits {
        return Err(malformed(&format!("tensor `{name}` has a shape signature that does not fit its shape")));
    }
    buffer(tensor.get::<u32>(2).unwrap_or(0))?;
    let quantization = tensor.get::<ForwardsUOffset<Table<'_>>>(4).map(|q| Fields::new(q, "QuantizationParameters", 7));
    let refusal = if tensor.get::<bool>(5).unwrap_or(false) {
        "is a variable"
    } else if tensor.has(6) {
        "is sparse"
    } else if tensor.len::<u32>(9) > 0 {
        "has variant subtypes"
    } else if tensor.get::<u32>(10).unwrap_or(0) != 0 {
        "keeps its data in an external buffer"
    } else if quantization.transpose()?.is_some_and(|q| q.has(4) || q.has(5)) {
        "has quantization other than affine"
    } else {
        return Ok(());
    };
    Err(refused(format!("tensor `{name}` {refusal}")))
}

/// The graph's input or output tensor indices: 1 to `MAX_PORTS`, valid and unique; ports carry no data and no
/// quantization. An empty quantization table (no min, max, scale, zero point or details) is no quantization: the
/// TFLite converter writes one on float ports, MediaPipe's face landmark graph among them.
fn ports(
    subgraph: Fields<'_>,
    slot: u16,
    kind: &str,
    tensors: &[Fields<'_>],
    buffers: &[Fields<'_>],
) -> Result<Vec<usize>, LoadError> {
    let list = subgraph.ints(slot);
    if list.is_empty() || list.len() > MAX_PORTS {
        return Err(refused(format!("{} graph {kind}s; a model has 1 to MAX_PORTS ({MAX_PORTS})", list.len())));
    }
    let mut seen = BTreeSet::new();
    let mut indices = Vec::with_capacity(list.len());
    for index in list {
        let i = index_in(u32::try_from(index).unwrap_or(u32::MAX), tensors.len(), "tensor")?;
        if !seen.insert(i) {
            return Err(malformed(&format!("tensor {i} is listed twice as a graph {kind}")));
        }
        let buffer = index_in(tensors[i].get::<u32>(2).unwrap_or(0), buffers.len(), "buffer")?;
        if buffers[buffer].len::<u8>(0) > 0 || quantized(tensors[i])? {
            return Err(refused(format!("graph {kind} {i} is a constant or quantized")));
        }
        indices.push(i);
    }
    Ok(indices)
}

/// A graph port's spec: a `DType`, a known rank and a name.
/// Whether `tensor` carries quantization: a quantization table with any min, max, scale, zero point or details.
fn quantized(tensor: Fields<'_>) -> Result<bool, LoadError> {
    let table = tensor.get::<ForwardsUOffset<Table<'_>>>(4).map(|q| Fields::new(q, "QuantizationParameters", 7));
    Ok(table.transpose()?.is_some_and(|q| {
        q.len::<f32>(0) > 0 || q.len::<f32>(1) > 0 || q.len::<f32>(2) > 0 || q.len::<i64>(3) > 0 || q.has(4) || q.has(5)
    }))
}

fn port_spec(tensor: Fields<'_>) -> Result<TensorSpec, LoadError> {
    let name = tensor.get::<ForwardsUOffset<&str>>(3).unwrap_or("");
    // LiteRT hands names back as C strings, so a NUL inside one would cut it short there.
    if name.is_empty() || name.len() > MAX_NAME_BYTES || name.contains('\0') {
        return Err(refused(format!(
            "a graph port named `{}`: a name is 1 to MAX_NAME_BYTES ({MAX_NAME_BYTES}) bytes, with no NUL",
            name.escape_debug()
        )));
    }
    let dtype = match tensor.get::<i8>(1).unwrap_or(0) {
        0 => DType::F32,
        2 => DType::I32,
        3 => DType::U8,
        4 => DType::I64,
        other => {
            return Err(LoadError::Format(format!(
                "`{name}` has element type {other}, which this runtime does not carry yet"
            )));
        }
    };
    let (shape, signature) = (tensor.ints(0), tensor.ints(7));
    if shape.is_empty() && !tensor.get::<bool>(8).unwrap_or(false) {
        return Err(refused(format!("graph port `{name}` has an unknown rank")));
    }
    let dims = if signature.is_empty() { &shape } else { &signature };
    // The tensor checks already refused negative `shape` entries; in `shape_signature` only -1 is negative.
    let shape = dims.iter().map(|&d| usize::try_from(d).map_or(Dim::ANY, Dim::Fixed)).collect::<Vec<_>>();
    Ok(TensorSpec::new(name, dtype, shape))
}

